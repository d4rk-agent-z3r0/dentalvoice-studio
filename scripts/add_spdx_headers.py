"""Add SPDX headers to original source files, idempotently.

Usage: python3 scripts/add_spdx_headers.py [--check]

Files listed in TEMPLATE_DERIVED or generated by tools are deliberately left without a project
copyright header (see docs/ownership-and-provenance.md). Empty files (package markers) are skipped.
--check exits non-zero if any eligible file lacks a header, for use in CI.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

COPYRIGHT = "SPDX-FileCopyrightText: 2026 Siddharth Majhi"
LICENSE_ID = "SPDX-License-Identifier: MIT"

HASH_COMMENT = (".py", ".sh", ".yml", ".yaml", ".toml")
HASH_COMMENT_NAMES = ("Dockerfile", "Makefile")
SLASH_COMMENT = (".ts", ".tsx", ".mts", ".js", ".mjs")
BLOCK_COMMENT = (".css",)

# Kept as generated by create-next-app (MIT, Vercel) or by tools; not claimed as original work.
TEMPLATE_DERIVED = {
    "frontend/eslint.config.mjs",
    "frontend/next.config.ts",
    "frontend/next-env.d.ts",
    "frontend/pnpm-workspace.yaml",
}
# Machine-generated files: never edited by hand.
GENERATED_NAMES = {"pnpm-lock.yaml", "uv.lock", "package-lock.json"}
# Lines that must stay first in their file.
PINNED_FIRST_LINE_PREFIXES = ("#!", "# syntax=")


def header_lines(path: Path) -> list[str] | None:
    name, suffix = path.name, path.suffix
    if suffix in HASH_COMMENT or name in HASH_COMMENT_NAMES:
        return [f"# {COPYRIGHT}", f"# {LICENSE_ID}"]
    if suffix in SLASH_COMMENT:
        return [f"// {COPYRIGHT}", f"// {LICENSE_ID}"]
    if suffix in BLOCK_COMMENT:
        return [f"/* {COPYRIGHT} */", f"/* {LICENSE_ID} */"]
    return None


def eligible_files(root: Path) -> list[Path]:
    tracked = subprocess.run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard"],  # noqa: S607
        cwd=root,
        check=True,
        capture_output=True,
        text=True,
    ).stdout.splitlines()
    files = []
    for rel in tracked:
        path = root / rel
        if rel in TEMPLATE_DERIVED or path.name in GENERATED_NAMES:
            continue
        if not path.is_file() or path.stat().st_size == 0:
            continue
        if header_lines(path) is not None:
            files.append(path)
    return files


def has_header(text: str) -> bool:
    return LICENSE_ID in "\n".join(text.splitlines()[:5])


def add_header(path: Path) -> bool:
    text = path.read_text(encoding="utf-8")
    if has_header(text):
        return False
    lines = text.splitlines(keepends=True)
    pinned: list[str] = []
    if lines and lines[0].startswith(PINNED_FIRST_LINE_PREFIXES):
        pinned = [lines.pop(0)]
    header = [line + "\n" for line in header_lines(path) or []]
    path.write_text("".join(pinned + header + lines), encoding="utf-8")
    return True


def main() -> int:
    root = Path(__file__).resolve().parents[1]
    check = "--check" in sys.argv[1:]
    missing = [p for p in eligible_files(root) if not has_header(p.read_text(encoding="utf-8"))]
    if check:
        for path in missing:
            print(f"missing SPDX header: {path.relative_to(root)}")
        return 1 if missing else 0
    for path in missing:
        add_header(path)
        print(f"added SPDX header: {path.relative_to(root)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
