"""Generate the synthetic caller audio clips from the scenario transcripts.

Two engines, chosen by the owner (2026-10-31):

- ``espeak`` (default): eSpeak NG, offline, deterministic. Output is committed to
  ``backend/demo_data/audio/fixtures/`` with a manifest of hashes, so the demo works with no keys.
  The voices sound robotic.
- ``deepgram``: Deepgram Aura text-to-speech, natural voices. Needs ``DEEPGRAM_API_KEY``. Output
  goes to ``backend/demo_data/audio/local/``, which is git-ignored and never committed (Deepgram's
  terms for redistributing generated audio have not been reviewed). The server prefers these
  files when they exist.

    python3 scripts/generate_audio_fixtures.py            # espeak, writes fixtures + manifest
    python3 scripts/generate_audio_fixtures.py --check    # verify committed fixtures are current
    DEEPGRAM_API_KEY=... python3 scripts/generate_audio_fixtures.py --engine deepgram

All audio is 16 kHz, mono, 16-bit PCM WAV: the format streamed to speech-to-text.
Run from the repository root; it imports the catalogue from ``backend/``.
"""

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AUDIO = ROOT / "backend" / "demo_data" / "audio"
FIXTURES = AUDIO / "fixtures"
LOCAL = AUDIO / "local"
MANIFEST = FIXTURES / "manifest.json"
SAMPLE_RATE = 16_000

# eSpeak NG voice per persona (its own GPL voice data; the separately licensed MBROLA voices are
# deliberately not used). Variants give each caller a distinguishable voice.
ESPEAK_VOICES = {
    "ava": "en-us+f3",
    "marcus": "en-us+m3",
    "elena": "en-gb+f2",
    "jordan": "en-us+m5",
    "noah": "en-gb+m2",
    "priya": "en-us+f4",
}
ESPEAK_SPEED = 150  # words per minute
DEEPGRAM_VOICES = {  # Aura voice per persona; confirm current ids in Deepgram's docs
    "ava": "aura-2-thalia-en",
    "marcus": "aura-2-apollo-en",
    "elena": "aura-2-andromeda-en",
    "jordan": "aura-2-arcas-en",
    "noah": "aura-2-orion-en",
    "priya": "aura-2-luna-en",
}


def _clips() -> list[tuple[str, str, str]]:
    """(clip id, persona key, transcript) for every scripted caller clip."""
    sys.path.insert(0, str(ROOT / "backend"))
    from app.demo import catalog

    rows = []
    for clinic in catalog.CLINICS:
        for scenario in clinic.scenarios:
            for clip in scenario.clips:
                rows.append((clip.id, scenario.persona_key, clip.transcript))
    return sorted(rows)


def _text_hash(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _file_hash(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _to_pcm16_wav(source: Path, target: Path) -> None:
    """Resample to 16 kHz mono s16 and strip metadata, so output is byte-reproducible."""
    subprocess.run(  # noqa: S603 - fixed argv, no shell
        [
            shutil.which("ffmpeg") or "ffmpeg",
            "-loglevel", "error", "-y", "-i", str(source),
            "-ac", "1", "-ar", str(SAMPLE_RATE), "-sample_fmt", "s16",
            "-map_metadata", "-1", "-fflags", "+bitexact", "-flags:a", "+bitexact",
            str(target),
        ],
        check=True,
    )  # fmt: skip


def _espeak(text: str, voice: str, target: Path) -> None:
    with tempfile.TemporaryDirectory() as tmp:
        raw = Path(tmp) / "raw.wav"
        subprocess.run(  # noqa: S603 - fixed argv, no shell
            [shutil.which("espeak-ng") or "espeak-ng", "-v", voice, "-s", str(ESPEAK_SPEED),
             "-w", str(raw), text],
            check=True,
        )  # fmt: skip
        _to_pcm16_wav(raw, target)


def _deepgram(text: str, voice: str, target: Path, api_key: str) -> None:
    url = (
        "https://api.deepgram.com/v1/speak"
        f"?model={voice}&encoding=linear16&sample_rate={SAMPLE_RATE}&container=wav"
    )
    request = urllib.request.Request(  # noqa: S310 - fixed https URL
        url,
        data=json.dumps({"text": text}).encode(),
        headers={"Authorization": f"Token {api_key}", "Content-Type": "application/json"},
        method="POST",
    )
    with tempfile.TemporaryDirectory() as tmp, urllib.request.urlopen(request, timeout=30) as resp:  # noqa: S310
        raw = Path(tmp) / "raw.wav"
        raw.write_bytes(resp.read())
        _to_pcm16_wav(raw, target)


def manifest_for(clips: list[tuple[str, str, str]]) -> dict[str, object]:
    return {
        "_comment": "Generated by scripts/generate_audio_fixtures.py. Do not edit by hand.",
        "engine": "espeak-ng",
        "speed_wpm": ESPEAK_SPEED,
        "format": {"sample_rate": SAMPLE_RATE, "channels": 1, "sample_format": "s16le"},
        "clips": {
            clip_id: {
                "persona": persona,
                "voice": ESPEAK_VOICES[persona],
                "text_sha256": _text_hash(text),
                "audio_sha256": _file_hash(FIXTURES / f"{clip_id}.wav"),
            }
            for clip_id, persona, text in clips
        },
    }


def check(clips: list[tuple[str, str, str]]) -> list[str]:
    """Problems with the committed fixtures: missing, stale transcript, or modified audio."""
    problems = []
    if not MANIFEST.exists():
        return [f"{MANIFEST.relative_to(ROOT)} is missing"]
    recorded = json.loads(MANIFEST.read_text())["clips"]
    for clip_id, persona, text in clips:
        entry = recorded.get(clip_id)
        path = FIXTURES / f"{clip_id}.wav"
        if entry is None or not path.exists():
            problems.append(f"{clip_id}: no fixture")
        elif entry["text_sha256"] != _text_hash(text) or entry["voice"] != ESPEAK_VOICES[persona]:
            problems.append(f"{clip_id}: transcript or voice changed since the audio was generated")
        elif entry["audio_sha256"] != _file_hash(path):
            problems.append(f"{clip_id}: audio file does not match the manifest")
    extra = set(recorded) - {clip_id for clip_id, _, _ in clips}
    problems += [
        f"{clip_id}: fixture for a clip that no longer exists" for clip_id in sorted(extra)
    ]
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--engine", choices=["espeak", "deepgram"], default="espeak")
    parser.add_argument("--check", action="store_true", help="verify committed fixtures only")
    args = parser.parse_args()
    clips = _clips()

    if args.check:
        problems = check(clips)
        for problem in problems:
            print(problem)
        print(f"{len(clips)} clips, {len(problems)} problems")
        return 1 if problems else 0

    if args.engine == "espeak":
        FIXTURES.mkdir(parents=True, exist_ok=True)
        for stale in FIXTURES.glob("*.wav"):
            stale.unlink()
        for clip_id, persona, text in clips:
            _espeak(text, ESPEAK_VOICES[persona], FIXTURES / f"{clip_id}.wav")
        MANIFEST.write_text(json.dumps(manifest_for(clips), indent=2, sort_keys=True) + "\n")
        print(f"wrote {len(clips)} fixtures and {MANIFEST.relative_to(ROOT)}")
        return 0

    api_key = os.environ.get("DEEPGRAM_API_KEY", "").strip()
    if not api_key:
        print("DEEPGRAM_API_KEY is not set (put it in your environment, never in the repo).")
        return 2
    LOCAL.mkdir(parents=True, exist_ok=True)
    for clip_id, persona, text in clips:
        _deepgram(text, DEEPGRAM_VOICES[persona], LOCAL / f"{clip_id}.wav", api_key)
    print(f"wrote {len(clips)} Deepgram clips to {LOCAL.relative_to(ROOT)} (git-ignored)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
